#!/usr/bin/env node
// "What models work today": a Markdown table built from the built-in presets, so the README never
// lists a model the app cannot run.
//
//   node scripts/models-table.mjs           # rewrite the table in README.md (between the models markers)
//   node scripts/models-table.mjs --check   # exit 1 when README.md is out of date
//   node scripts/models-table.mjs --print   # print the table
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { builtInPresets } from '../server/previs/presets.mjs';
import { imagePresets } from '../server/previs/refgen.mjs';

export const README = fileURLToPath(new URL('../README.md', import.meta.url));
export const START = '<!-- models:start (generated by scripts/models-table.mjs; do not edit by hand) -->';
export const END = '<!-- models:end -->';

const INPUT = { firstFrame: 'start key frame', lastFrame: 'end key frame', sourceVideo: 'blockout video', controlVideo: 'blockout video (as control frames)', maskVideo: 'mask video', prompt: 'prompt' };
const USE = {
  'first-frame': 'Video from key frames',
  'transform-video': 'Video from the blockout clip',
  'control-video': 'Video from the blockout clip',
  'masked-video-edit': 'Fixed-region crop edit of a take',
};
const money = n => `$${n < 0.1 ? n.toFixed(3) : n.toFixed(2)}`;
/** Prefer explicit backendRequirements.kinds when present (Cloud-only masked VACE). */
const local = p => {
  const kinds = p.backendRequirements?.kinds;
  if (Array.isArray(kinds) && kinds.length) {
    if (kinds.includes('cloud') && !kinds.includes('local')) return false;
    if (kinds.includes('local') && !kinds.includes('cloud')) return true;
  }
  return p.backend ? p.backend === 'local' : !(p.pricing?.ratePerSecond > 0);
};
const videoCost = p => {
  if (p.pricing?.ratePerSecond > 0) return `≈ ${money(p.pricing.ratePerSecond)} / s`;
  if (local(p)) return 'free (your GPU)';
  if (p.pricing?.status === 'unknown') return 'planning estimate (quoted live)';
  return 'quoted live';
};
const videoInputs = p => {
  if (p.task === 'masked-video-edit') return 'source crop, mask video, prompt';
  return Object.keys(p.inputs || {}).map(k => INPUT[k] || k).join(', ');
};

/** Rows for every built-in image and video preset, images first. */
export function modelRows() {
  const images = imagePresets.map(p => ({
    model: p.title, use: 'Looks, sheets and stills', runs: local(p) ? 'Your ComfyUI' : 'Comfy Cloud',
    inputs: ['prompt', p.maxRefs ? `up to ${p.maxRefs} cast images` : null, 'blockout frame (stills)'].filter(Boolean).join(', '),
    cost: p.pricing?.usdPerImage > 0 ? `≈ ${money(p.pricing.usdPerImage)} / image` : local(p) ? 'free (your GPU)' : 'quoted live',
  }));
  const videos = builtInPresets.map(p => ({
    model: p.title, use: USE[p.task] || p.task, runs: local(p) ? 'Your ComfyUI' : 'Comfy Cloud',
    inputs: videoInputs(p),
    cost: videoCost(p),
  }));
  return [...images, ...videos];
}

export function modelsTable() {
  const rows = modelRows().map(r => `| ${r.model} | ${r.use} | ${r.runs} | ${r.inputs} | ${r.cost} |`);
  return ['| Model | Used for | Runs on | Takes | List-price estimate |', '|---|---|---|---|---|', ...rows].join('\n');
}

/** README text with the generated table between the markers. */
export function withTable(readme) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw Error(`README.md has no ${START} … ${END} block`);
  return `${readme.slice(0, a + START.length)}\n${modelsTable()}\n${readme.slice(b)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  if (args.includes('--print')) console.log(modelsTable());
  else {
    const before = await readFile(README, 'utf8'), after = withTable(before);
    if (args.includes('--check')) { if (before !== after) { console.error('README.md models table is out of date: run pnpm docs:models'); process.exit(1); } }
    else if (before !== after) { await writeFile(README, after); console.log('README.md models table updated'); }
    else console.log('README.md models table is up to date');
  }
}
